/**
 * Recursively finds all string values in an object and their paths
 */
function findStringValues(obj, path = "", results = []) {
  for (const [key, value] of Object.entries(obj)) {
    const currentPath = path ? `${path}.${key}` : key;

    if (typeof value === "string") {
      results.push({ path: currentPath, value });
    } else if (value && typeof value === "object" && !Array.isArray(value)) {
      findStringValues(value, currentPath, results);
    }
  }
  return results;
}

/**
 * Sets a nested value in an object using dot notation path
 */
function setNestedValue(obj, path, value) {
  const keys = path.split(".");
  let current = obj;

  for (let i = 0; i < keys.length - 1; i++) {
    if (!current[keys[i]] || typeof current[keys[i]] !== "object") {
      current[keys[i]] = {};
    }
    current = current[keys[i]];
  }

  current[keys[keys.length - 1]] = value;
}

/**
 * Gets a nested value from an object using dot notation path
 */
function getNestedValue(obj, path) {
  const keys = path.split(".");
  let current = obj;

  for (const key of keys) {
    if (current && typeof current === "object" && key in current) {
      current = current[key];
    } else {
      return undefined;
    }
  }

  return current;
}

const BASE_PATH = "./src/locales/en-US";
const LOCALES_DIR = "./src/locales";
const locales = ["ar", "be", "de", "en-GB", "es", "fr", "hy", "it", "ja", "nb", "pl", "pt", "ru", "tr", "uk", "zh"];

console.log("Translating English texts in common.json files...\n");

// Load base English translations
const baseCommonPath = path.join(BASE_PATH, "common.json");
const baseCommon = JSON.parse(fs.readFileSync(baseCommonPath, "utf8"));
const baseStrings = findStringValues(baseCommon);

let totalTranslated = 0;

for (const locale of locales) {
  if (locale === "en-US" || locale === "en-GB") {
    continue; // Skip English variants
  }

  const commonPath = path.join(LOCALES_DIR, locale, "common.json");

  if (!fs.existsSync(commonPath)) {
    console.log(`[${locale}] No common.json, skipping`);
    continue;
  }

  try {
    const common = JSON.parse(fs.readFileSync(commonPath, "utf8"));
    const _localeStrings = findStringValues(common);
    const translations = TRANSLATIONS[locale] || {};
    let translatedCount = 0;

    // Find strings that match English base but should be translated
    for (const baseStr of baseStrings) {
      const localeValue = getNestedValue(common, baseStr.path);

      // If the value exists and matches the English version exactly, translate it
      if (localeValue && typeof localeValue === "string" && localeValue === baseStr.value) {
        // Check if we have a translation for this text
        if (translations[baseStr.value]) {
          setNestedValue(common, baseStr.path, translations[baseStr.value]);
          translatedCount++;
        }
      }
    }

    if (translatedCount > 0) {
      fs.writeFileSync(commonPath, `${JSON.stringify(common, null, 2)}\n`, "utf8");
      console.log(`[${locale}] ✓ Translated ${translatedCount} strings`);
      totalTranslated += translatedCount;
    } else {
      console.log(`[${locale}] No translations needed (or no translation mappings available)`);
    }
  } catch (error) {
    console.error(`[${locale}] ✗ Error:`, error.message);
  }
}

console.log(`\n✅ Done! Total strings translated: ${totalTranslated}`);
